const EYE = '#120806';
function legs(f, xs, top, bot, c, paw, w=2.2){
  const sw = [0,2,-2][f], far = [], near = [];
  xs.forEach((x,i) => {
    const s = (i===0||i===3) ? sw : -sw, out = i<2 ? far : near;
    out.push({l:[x, top, x+s, bot-1, w], c: i<2 ? [c[0],c[0],c[1]] : c});
    if(paw) out.push({r:[Math.round(x+s-1), bot-1, 3, 1], c:paw});
  });
  return {far, near};
}

